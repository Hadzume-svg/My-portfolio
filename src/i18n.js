export function makeI18n(lang) {
  const ui = UI[lang] || UI.ru;
  const t = (key) => {
    let cur = ui;
    for (const part of key.split(".")) {
      if (cur && typeof cur === "object" && part in cur) cur = cur[part];
      else return UI.ru[key] || key;
    }
    return cur;
  };
  const tr = (text) => {
    if (!text || typeof text !== "string") return text;
    const hit = CONTENT.find((r) => r.ru === text);
    return hit && hit[lang] ? hit[lang] : text;
  };
  return { t, tr };
}

